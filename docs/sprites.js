// Converte um sprite em retangulos SVG, agrupando pixels vizinhos na horizontal
// (run-length) para nao gerar centenas de <rect> por desenho.
export function spriteToRects(sprite, { x = 0, y = 0, px = 1, fill = 'currentColor' } = {}) {
  const out = []
  sprite.forEach((row, ry) => {
    let run = 0
    for (let cx = 0; cx <= row.length; cx++) {
      if (row[cx] === '#') { run++; continue }
      if (run > 0) {
        const startX = x + (cx - run) * px
        out.push(
          `<rect x="${startX}" y="${y + ry * px}" width="${run * px}" height="${px}" fill="${fill}"/>`
        )
        run = 0
      }
    }
  })
  return out.join('')
}

export function assertRectangular(name, sprite) {
  const w = sprite[0].length
  sprite.forEach((row, i) => {
    if (row.length !== w) {
      throw new Error(`${name}: linha ${i} tem ${row.length} chars, esperado ${w}`)
    }
  })
  return { name, w, h: sprite.length }
}
